"""Render a Phase-0 template into a self-checking AArch64 guest.

The guest prints ``template=<id> ... status=PASS|FAIL`` and a standalone
16-hex checksum line (the format ``tools/classify.py`` expects).  The expected
checksum is computed by the Python reference interpreter in ``isa.py`` before
the guest is built, so the guest cannot "pass" by reusing its own arithmetic.
"""

from dataclasses import replace

from . import isa
from .templates import Template

REPS_PER_ITERATION = 16
DEFAULT_ITERATIONS = 200


def display_operand(template):
    """Constant loaded into x12 by the template setup, or None."""
    for op in template.setup:
        if op.kind == "mov" and op.dst == "x12":
            return op.imm
    return None


def with_operand(template, register, value):
    """Return a copy of *template* whose setup loads *value* into *register*."""
    setup = tuple(
        isa.Op("mov", dst=register, imm=value)
        if op.kind == "mov" and op.dst == register else op
        for op in template.setup
    )
    return replace(template, setup=setup)


def memory_initializer(memory):
    words = ",\n    ".join(f"0x{word:016x}ULL" for word in memory)
    return f"static uint64_t data[{isa.MEM_WORDS}] __attribute__((aligned(64))) = {{\n    {words},\n}};"


def asm_lines(template):
    """Assembler lines (without C escaping) for the template's ROI body."""
    lines = []
    for reg in isa.GPRS:
        lines.append(f"movz {reg}, #0x0")
    for reg in isa.FPREGS:
        lines.append(f"fmov {reg}, xzr")
    for op in template.setup:
        lines.extend(isa.render(op))
    lines.append("mov x14, %[n]")
    lines.append("9:")
    lines.append(f".rept {REPS_PER_ITERATION}")
    for op in template.body:
        lines.extend(isa.render(op))
    lines.append(".endr")
    lines.append("subs x14, x14, #1")
    lines.append("b.ne 9b")
    for reg in isa.GPRS:
        lines.append(f"mov %[o{reg[1:]}], {reg}")
    for reg in isa.FPREGS:
        lines.append(f"fmov %[f{reg[1:]}], {reg}")
    return lines


def render_guest(template: Template, iterations=DEFAULT_ITERATIONS,
                 operand=None):
    """Return ``(c_source, expected_checksum)`` for one template."""
    if iterations <= 0:
        raise ValueError("iterations must be positive")
    if operand is not None:
        template = with_operand(template, "x12", operand)
    expected = isa.expected_checksum(template, iterations)
    asm_body = "".join(f'        "{line}\\n\\t"\n' for line in asm_lines(template))
    outputs = ",\n        ".join(
        [f'[o{reg[1:]}] "=r"(o{reg[1:]})' for reg in isa.GPRS]
        + [f'[f{reg[1:]}] "=r"(f{reg[1:]})' for reg in isa.FPREGS])
    clobbers = ", ".join(f'"{reg}"' for reg in isa.GPRS + isa.FPREGS + ("x14",))
    declarations = "\n".join(
        [f"    uint64_t o{reg[1:]} = 0;" for reg in isa.GPRS]
        + [f"    uint64_t f{reg[1:]} = 0;" for reg in isa.FPREGS])
    mix_calls = "\n".join(
        [f"    h = mix(h, o{reg[1:]});" for reg in isa.GPRS]
        + [f"    h = mix(h, f{reg[1:]});" for reg in isa.FPREGS])
    source = f"""/* Generated by sdcfuzz/generator.py from template {template.id}.
 * Expected checksum is computed by the Python reference interpreter, not by
 * this program.  Do not edit generated files; edit the template instead. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#include <gem5/m5ops.h>

#if !defined(__aarch64__)
#error "generated baseline guest requires AArch64"
#endif

#define ITERATIONS {iterations}ULL
#define EXPECTED_CHECKSUM 0x{expected:016x}ULL

{memory_initializer(isa.initial_memory())}

static uint64_t
mix(uint64_t h, uint64_t v)
{{
    return (h ^ v) * 1099511628211ULL;
}}

int
main(void)
{{
{declarations}
    uint64_t *buffer = data;
    uint64_t h = 1469598103934665603ULL;

    m5_work_begin(7, 0);
    __asm__ volatile(
{asm_body}        :
        {outputs}
        : [n] "r"(ITERATIONS), [buf] "r"(buffer)
        : {clobbers}, "cc", "memory");
    m5_work_end(7, 0);

{mix_calls}
    for (unsigned index = 0; index < {isa.MEM_WORDS}; ++index)
        h = mix(h, data[index]);

    printf("template={template.id} target={template.target} "
           "status=%s\\n", h == EXPECTED_CHECKSUM ? "PASS" : "FAIL");
    printf("%016llx\\n", (unsigned long long)h);
    return h == EXPECTED_CHECKSUM ? 0 : 1;
}}
"""
    return source, expected
