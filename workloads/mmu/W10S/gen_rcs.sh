#!/usr/bin/env bash
# gen_rcs.sh — build a self-contained, single-variant W10S rcS.
#
# The formal Excel WorkloadID for this arm stays W10.  W10S is an internal
# Variant of W10; the two store arms are selected here:
#
#   --mode cold : W10S-COLD-STORE  (M06 R02, EL0 write / cold write walk)
#   --mode warm : W10S-WARM-STORE  (M08 R05, STRB / warm DTLB hit)
#
# The target VA is an input of this generator and becomes the single
# W10S_TARGET_VA parameter line in the produced rcS; the workload binary
# receives it through `--target-va` at run time.  Nothing about the target
# VA is compiled into mmu_w10s.
#
# Usage:
#   gen_rcs.sh --mode warm|cold --target-va 0x... --out FILE [options]
#
# Options:
#   --binary PATH     workload ELF (default: <script dir>/mmu_w10s)
#   --variant NAME    label printed in the rcS (default derived from mode)
#   --buffer-va 0x... buffer base VA (default 0x4002000000)
#   --pages N         initial page count (default 4096)
#   --max-pages N     expansion cap (default 65536)
#   --file-dir DIR    guest backing directory (default /var/tmp/w10s)
#
# The generated script embeds the exact binary bytes (gzip -9n | base64), so
# the run cannot silently use a stale workload.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
mode=""
target_va=""
out=""
binary="$here/mmu_w10s"
variant=""
buffer_va="0x4002000000"
pages="4096"
max_pages="65536"
file_dir="/var/tmp/w10s"

die() { echo "gen_rcs: $*" >&2; exit 2; }

while [ $# -gt 0 ]; do
    case "$1" in
        --mode)       mode=${2:?}; shift 2 ;;
        --target-va)  target_va=${2:?}; shift 2 ;;
        --binary)     binary=${2:?}; shift 2 ;;
        --variant)    variant=${2:?}; shift 2 ;;
        --buffer-va)  buffer_va=${2:?}; shift 2 ;;
        --pages)      pages=${2:?}; shift 2 ;;
        --max-pages)  max_pages=${2:?}; shift 2 ;;
        --file-dir)   file_dir=${2:?}; shift 2 ;;
        --out)        out=${2:?}; shift 2 ;;
        -h|--help)    sed -n '2,30p' "$0"; exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
done

[ "$mode" = "warm" ] || [ "$mode" = "cold" ] || die "--mode must be warm|cold"
[ -n "$target_va" ] || die "--target-va is required"
[ -n "$out" ] || die "--out is required"
[ -x "$binary" ] || die "not executable: $binary"
[ -f "$binary" ] || die "not a file: $binary"

# 4 KiB alignment and 39-bit user VA sanity (the workload repeats the check).
tv=$(( target_va ))
[ $(( tv % 4096 )) -eq 0 ] || die "--target-va $target_va is not 4 KiB aligned"
[ "$tv" -lt $((1 << 39)) ] || die "--target-va $target_va exceeds 39-bit user VA"
[ -n "$variant" ] || {
    if [ "$mode" = "cold" ]; then variant="W10S-COLD-STORE"
    else variant="W10S-WARM-STORE"; fi
}

sha=$(sha256sum "$binary" | awk '{print $1}')
payload=$(gzip -9n -c "$binary" | base64)

tmp=$(mktemp "${out}.tmp.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
    echo '#!/bin/sh'
    echo "# Generated by workloads/mmu/W10S/gen_rcs.sh — do not edit by hand."
    echo "# Formal WorkloadID: W10   internal Variant: $variant"
    echo "# Workload binary SHA256: $sha"
    echo "# TargetVA is supplied at run time (see W10S_TARGET_VA below)."
    echo 'echo "[mmu-w10s] install"'
    echo "base64 -d > /tmp/mmu-w10s.gz <<'MMU_W10S_B64'"
    printf '%s\n' "$payload"
    echo 'MMU_W10S_B64'
    echo 'if ! gzip -dc /tmp/mmu-w10s.gz > /tmp/mmu-w10s; then'
    echo '  echo "[mmu-w10s] FATAL payload decode failed"'
    echo '  m5 exit'
    echo 'fi'
    echo 'chmod +x /tmp/mmu-w10s'
    echo "BUF_DIR=$file_dir"
    echo 'mkdir -p "$BUF_DIR" 2>/dev/null || BUF_DIR=/tmp'
    echo '[ -w "$BUF_DIR" ] || BUF_DIR=/tmp'
    echo 'echo "[mmu-w10s] buffer_dir=$BUF_DIR"'
    echo "# ---- run-time variant parameters ----"
    echo "W10S_VARIANT=$variant"
    echo "W10S_MODE=$mode"
    echo "W10S_TARGET_VA=$target_va"
    echo "W10S_BUFFER_VA=$buffer_va"
    echo "W10S_PAGES=$pages"
    echo "W10S_MAX_PAGES=$max_pages"
    echo 'echo "[mmu-w10s] variant=$W10S_VARIANT mode=$W10S_MODE target_va=$W10S_TARGET_VA"'
    echo 'if command -v timeout >/dev/null 2>&1; then'
    echo '  timeout -s KILL 60 /tmp/mmu-w10s --"$W10S_MODE" \'
    echo '    --target-va "$W10S_TARGET_VA" --buffer-va "$W10S_BUFFER_VA" \'
    echo '    --pages "$W10S_PAGES" --max-pages "$W10S_MAX_PAGES" \'
    echo '    --file-dir "$BUF_DIR"'
    echo 'else'
    echo '  /tmp/mmu-w10s --"$W10S_MODE" \'
    echo '    --target-va "$W10S_TARGET_VA" --buffer-va "$W10S_BUFFER_VA" \'
    echo '    --pages "$W10S_PAGES" --max-pages "$W10S_MAX_PAGES" \'
    echo '    --file-dir "$BUF_DIR"'
    echo 'fi'
    echo 'echo "[mmu-w10s] variant=$W10S_VARIANT rc=$?"'
    echo 'm5 exit'
} > "$tmp"
chmod +x "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "gen_rcs: wrote $out (target_va=$target_va mode=$mode binary_sha256=$sha)"
